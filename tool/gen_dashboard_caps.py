#!/usr/bin/env python3
"""Generate dashboard_core's capability registry from the web dashboard's.

    tool/gen_dashboard_caps.py [--web <MadarDashboard dir>] [--check]

Source: MadarDashboard/src/generated/capabilities.ts (itself generated by
authz-gen from MadarRust's capabilities.toml) for the `Cap` names and keys, the
per-capability metadata, the groups and the role labels; MadarDashboard's
src/config/nav.ts (`OrgModule`) and src/hooks/use-org-modules.ts
(`ALL_MODULES`) for the org modules.

Writes packages/dashboard_core/lib/src/generated/capabilities.dart. `--check`
writes nothing and exits 1 when that file is stale. Standard library only.
"""
import argparse
import os
import re
import shutil
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_WEB = "/Users/shawket/Desktop/Madar/MadarDashboard"
OUT = os.path.join(ROOT, "packages", "dashboard_core", "lib", "src", "generated", "capabilities.dart")


# ── a tiny reader for the JS object/array literals in the .ts file ───────────

class Lit:
    def __init__(self, s, i=0):
        self.s, self.i = s, i

    def ws(self):
        while self.i < len(self.s):
            c = self.s[self.i]
            if c.isspace():
                self.i += 1
            elif self.s.startswith("//", self.i):
                self.i = self.s.index("\n", self.i)
            elif self.s.startswith("/*", self.i):
                self.i = self.s.index("*/", self.i) + 2
            else:
                break

    def value(self):
        self.ws()
        c = self.s[self.i]
        if c == "{":
            return self.obj()
        if c == "[":
            return self.arr()
        if c in "\"'":
            return self.string()
        m = re.compile(r"-?\d+(\.\d+)?").match(self.s, self.i)
        if m:
            self.i = m.end()
            return float(m.group()) if m.group(1) else int(m.group())
        m = re.compile(r"[A-Za-z_$][\w$]*").match(self.s, self.i)
        if m:
            self.i = m.end()
            word = m.group()
            return {"null": None, "true": True, "false": False}.get(word, word)
        raise SystemExit(f"unexpected {self.s[self.i:self.i + 40]!r}")

    def string(self):
        q = self.s[self.i]
        self.i += 1
        out = []
        while self.s[self.i] != q:
            c = self.s[self.i]
            if c == "\\":
                n = self.s[self.i + 1]
                if n == "u":
                    out.append(chr(int(self.s[self.i + 2:self.i + 6], 16)))
                    self.i += 6
                    continue
                out.append({"n": "\n", "t": "\t", "r": "\r"}.get(n, n))
                self.i += 2
                continue
            out.append(c)
            self.i += 1
        self.i += 1
        return "".join(out)

    def key(self):
        self.ws()
        if self.s[self.i] in "\"'":
            return self.string()
        m = re.compile(r"[A-Za-z_$][\w$]*").match(self.s, self.i)
        self.i = m.end()
        return m.group()

    def obj(self):
        self.i += 1
        out = {}
        while True:
            self.ws()
            if self.s[self.i] == "}":
                self.i += 1
                return out
            k = self.key()
            self.ws()
            assert self.s[self.i] == ":", self.s[self.i:self.i + 40]
            self.i += 1
            out[k] = self.value()
            self.ws()
            if self.s[self.i] == ",":
                self.i += 1

    def arr(self):
        self.i += 1
        out = []
        while True:
            self.ws()
            if self.s[self.i] == "]":
                self.i += 1
                return out
            out.append(self.value())
            self.ws()
            if self.s[self.i] == ",":
                self.i += 1


def literal_after(src, marker):
    at = src.index(marker) + len(marker)
    return Lit(src, at).value()


def dstr(s):
    if s is None:
        return "null"
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$").replace("\n", "\\n") + "'"


def dlist(xs):
    return "<String>[" + ", ".join(dstr(x) for x in xs) + "]"


def generate(web):
    ts = open(os.path.join(web, "src", "generated", "capabilities.ts"), encoding="utf-8").read()
    version = int(re.search(r"export const SPEC_VERSION = (\d+);", ts).group(1))
    spec_hash = re.search(r'export const SPEC_HASH = "([^"]+)";', ts).group(1)

    cap_block = ts[ts.index("export const Cap = {"):]
    cap_block = cap_block[:cap_block.index("} as const;")]
    caps = re.findall(r'^\s+(\w+): "([^"]+)" as Capability,', cap_block, re.M)
    if not caps:
        raise SystemExit("no Cap entries found")

    def union(name):
        m = re.search(rf"export type {name} =([^;]+);", ts)
        return re.findall(r"['\"]([^'\"]+)['\"]", m.group(1))

    role_kinds = union("RoleKind")
    tiers = union("CapabilityTier")
    risks = union("CapabilityRisk")
    limit_keys = union("LimitKey")
    metas = literal_after(ts, "export const CAPABILITIES: readonly CapabilityMeta[] = ")
    groups = literal_after(ts, "export const CAPABILITY_GROUPS: readonly { key: string; en: string; ar: string }[] = ")
    role_labels = literal_after(ts, "export const ROLE_KIND_LABELS: Record<RoleKind, { en: string; ar: string }> = ")

    nav = open(os.path.join(web, "src", "config", "nav.ts"), encoding="utf-8").read()
    modules = re.findall(r'"([^"]+)"', re.search(r"export type OrgModule = ([^;]+);", nav).group(1))
    mods_src = open(os.path.join(web, "src", "hooks", "use-org-modules.ts"), encoding="utf-8").read()
    all_modules = re.findall(r'"([^"]+)"', re.search(r"export const ALL_MODULES: readonly string\[\] = \[([^\]]*)\]", mods_src).group(1))

    def camel(s):
        parts = re.split(r"[_\-.]", s)
        return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])

    o = []
    w = o.append
    w("// GENERATED by tool/gen_dashboard_caps.py from MadarDashboard/src/generated/capabilities.ts")
    w(f"// (authz-gen, spec v{version}, hash {spec_hash}) and the org modules in src/config/nav.ts.")
    w("// DO NOT EDIT: re-run the tool.")
    w("// ignore_for_file: type=lint")
    w("")
    w(f"const int capabilitySpecVersion = {version};")
    w(f"const String capabilitySpecHash = {dstr(spec_hash)};")
    w("")
    w("/// Every capability key, under the web's `Cap.x` names. Gate on these,")
    w("/// never on a role name.")
    w("abstract final class Cap {")
    for name, key in caps:
        w(f"  static const String {name} = {dstr(key)};")
    w("")
    w("  /// `Cap` name -> key, in the web's order.")
    w("  static const Map<String, String> byName = <String, String>{")
    for name, key in caps:
        w(f"    {dstr(name)}: {dstr(key)},")
    w("  };")
    w("")
    w("  /// Every key, in the web's order.")
    w("  static const List<String> all = <String>[")
    for name, _ in caps:
        w(f"    {name},")
    w("  ];")
    w("}")
    w("")
    w("/// The role kinds a capability can default to (`RoleKind`).")
    w("abstract final class RoleKind {")
    for r in role_kinds:
        w(f"  static const String {camel(r)} = {dstr(r)};")
    w(f"  static const List<String> all = {dlist(role_kinds)};")
    w("}")
    w("")
    w(f"const List<String> capabilityTiers = {dlist(tiers)};")
    w(f"const List<String> capabilityRisks = {dlist(risks)};")
    w(f"const List<String> capabilityLimitKeys = {dlist(limit_keys)};")
    w("")
    w("/// One registry row (`CapabilityMeta`).")
    w("class CapabilityMeta {")
    w("  const CapabilityMeta({")
    fields = [
        ("int", "id", "id"), ("String", "key", "key"), ("String?", "legacy", "legacy"),
        ("String", "group", "group"), ("String", "tier", "tier"), ("String", "risk", "risk"),
        ("List<String>", "defaults", "defaults"), ("List<String>", "core", "core"),
        ("bool", "approval", "approval"), ("List<String>", "limits", "limits"), ("bool", "pos", "pos"),
        ("bool", "isProtected", "protected"), ("String", "en", "en"), ("String", "ar", "ar"),
        ("String?", "hintEn", "hintEn"), ("String?", "hintAr", "hintAr"),
    ]
    for t, n, _ in fields:
        w(f"    {'required ' if not t.endswith('?') else ''}this.{n},")
    w("  });")
    for t, n, _ in fields:
        w(f"  final {t} {n};")
    w("")
    w("  /// The label in [lang] (`en`/`ar`).")
    w("  String label(String lang) => lang.startsWith('ar') ? ar : en;")
    w("")
    w("  /// The hint in [lang], if any.")
    w("  String? hint(String lang) => lang.startsWith('ar') ? hintAr : hintEn;")
    w("}")
    w("")
    w("const List<CapabilityMeta> capabilityRegistry = <CapabilityMeta>[")
    for m in metas:
        parts = []
        for t, n, src in fields:
            v = m[src]
            if t.startswith("List"):
                parts.append(f"{n}: {dlist(v)}")
            elif t in ("String", "String?"):
                parts.append(f"{n}: {dstr(v)}")
            elif t == "bool":
                parts.append(f"{n}: {'true' if v else 'false'}")
            else:
                parts.append(f"{n}: {v}")
        w("  CapabilityMeta(" + ", ".join(parts) + "),")
    w("];")
    w("")
    w("/// A capability group (`CAPABILITY_GROUPS`).")
    w("class CapabilityGroup {")
    w("  const CapabilityGroup({required this.key, required this.en, required this.ar});")
    w("  final String key;")
    w("  final String en;")
    w("  final String ar;")
    w("  String label(String lang) => lang.startsWith('ar') ? ar : en;")
    w("}")
    w("")
    w("const List<CapabilityGroup> capabilityGroups = <CapabilityGroup>[")
    for g in groups:
        w(f"  CapabilityGroup(key: {dstr(g['key'])}, en: {dstr(g['en'])}, ar: {dstr(g['ar'])}),")
    w("];")
    w("")
    w("/// `ROLE_KIND_LABELS`: role kind -> (en, ar).")
    w("const Map<String, ({String en, String ar})> roleKindLabels = <String, ({String en, String ar})>{")
    for k, v in role_labels.items():
        w(f"  {dstr(k)}: (en: {dstr(v['en'])}, ar: {dstr(v['ar'])}),")
    w("};")
    w("")
    w("/// The org modules (PS-2): `pos` = selling, catalog, stock and their reports;")
    w("/// `dawam` = attendance, roster, payroll.")
    w("abstract final class OrgModule {")
    for mname in modules:
        w(f"  static const String {camel(mname)} = {dstr(mname)};")
    w("")
    w("  /// Every module: what a platform user with no org pinned sees (`ALL_MODULES`).")
    w(f"  static const List<String> all = {dlist(all_modules)};")
    w("}")
    return "\n".join(o) + "\n"


def dart_format(text):
    """The text as `dart format` writes it (the repo's CI checks formatting)."""
    if not shutil.which("dart"):
        return text
    with tempfile.TemporaryDirectory() as d:
        path = os.path.join(d, "capabilities.dart")
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
        subprocess.run(["dart", "format", "--language-version=3.11", path],
                       check=True, capture_output=True)
        with open(path, encoding="utf-8") as f:
            return f.read()


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("--web", default=DEFAULT_WEB)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    text = dart_format(generate(a.web))
    current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else None
    if current == text:
        return 0
    if a.check:
        print(f"stale: {OUT} (run tool/gen_dashboard_caps.py)", file=sys.stderr)
        return 1
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"wrote {os.path.relpath(OUT, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
