def build_ops(g):
    ops = []
    for path, item in g.spec["paths"].items():
        for method, o in item.items():
            op = Op()
            op.id, op.method, op.path, op.tag = o["operationId"], method.upper(), path, o["tags"][0]
            op.name = camel(op.id)
            op.summary, op.description = o.get("summary"), o.get("description")
            op.params = []
            used = set()
            for prm in o.get("parameters", []):
                t = g.resolve(prm.get("schema") or {}, pascal(op.id) + pascal(prm["name"]))
                req = prm.get("required", False) or prm["in"] == "path"
                nm = ident(prm["name"], PARAM_RESERVED)
                if nm == "body":
                    nm = "bodyParam"
                while nm in used:
                    nm += "_"
                used.add(nm)
                op.params.append({"in": prm["in"], "wire": prm["name"], "name": nm,
                                  "t": t if req else t.n(), "required": req,
                                  "doc": prm.get("description")})
            op.body = None
            rb = o.get("requestBody")
            if rb:
                ct, c = next(iter(rb["content"].items()))
                t = g.resolve(c.get("schema") or {}, pascal(op.id) + "Body")
                req = rb.get("required", False)
                op.body = {"ct": ct, "t": t if req else t.n(), "required": req}
            oks = sorted(c for c in o["responses"] if c.startswith("2"))
            r = o["responses"][oks[0]]
            content = r.get("content") or {}
            op.result = ("void", None)
            if "application/json" in content:
                op.result = ("json", g.resolve(content["application/json"].get("schema") or {},
                                                pascal(op.id) + "Response"))
            elif "text/event-stream" in content:
                op.result = ("stream", None)
            elif any(ct.startswith("text/") for ct in content):
                op.result = ("text", None)
            elif content:
                op.result = ("bytes", None)
            ops.append(op)
    ops.sort(key=lambda op: (op.tag, op.path, op.method))
    return ops


def tag_class(tag):
    return pascal(tag) + "Api"


def emit_op(op):
    out = []
    lines = []
    if op.summary:
        lines.append(op.summary)
    if op.description and op.description != op.summary:
        if lines:
            lines.append("")
        lines.append(op.description)
    if lines:
        lines.append("")
    lines.append(f"`{op.method} {op.path}` ({op.id})")
    out.append(doc("\n".join(lines), "  "))
    params = []
    for p in [p for p in op.params if p["required"]] + [p for p in op.params if not p["required"]]:
        req = "required " if p["required"] else ""
        params.append(f"{req}{p['t'].dart()} {p['name']},")
    if op.body:
        params.append(f"{'required ' if op.body['required'] else ''}{op.body['t'].dart()} body,")
    sig = ("{\n    " + "\n    ".join(params) + "\n  }") if params else ""
    kind, rt = op.result
    if kind == "json":
        ret = f"Future<{rt.dart()}>"
    elif kind == "stream":
        ret = "Stream<String>"
    elif kind == "text":
        ret = "Future<String>"
    elif kind == "bytes":
        ret = "Future<List<int>>"
    else:
        ret = "Future<void>"
    # path
    path = op.path
    for p in op.params:
        if p["in"] == "path":
            path = path.replace("{" + p["wire"] + "}", "${pathSegment(" + p["name"] + ")}")
    path_lit = "'" + path.replace("'", "\\'") + "'"
    query = []
    headers = []
    for p in op.params:
        val = p["name"]
        if p["in"] == "query":
            if p["t"].kind == "list":
                enc = f"[for (final v in {val}) queryValue(v)]"
            else:
                enc = f"[queryValue({val})]"
            if p["t"].nullable or p["t"].kind == "any":
                query.append(f"if ({val} != null) {dstr(p['wire'])}: {enc},")
            else:
                query.append(f"{dstr(p['wire'])}: {enc},")
        elif p["in"] == "header":
            v = f"queryValue({val})"
            if p["t"].nullable or p["t"].kind == "any":
                headers.append(f"if ({val} != null) {dstr(p['wire'])}: {v},")
            else:
                headers.append(f"{dstr(p['wire'])}: {v},")
    req_args = [f"method: {dstr(op.method)},", f"path: {path_lit},"]
    if query:
        req_args.append("query: {\n        " + "\n        ".join(query) + "\n      },")
    if op.body:
        bt = op.body["t"]
        if op.body["ct"] == "multipart/form-data" and bt.kind == "model":
            q = "?" if bt.nullable else ""
            req_args.append(f"body: body{q}.toJson(),")
            req_args.append(f"files: body{q}.toFiles() ?? const []," if bt.nullable else "files: body.toFiles(),")
        else:
            req_args.append(f"body: {encode(bt, 'body')},")
    if headers:
        req_args.append("headers: {\n        " + "\n        ".join(headers) + "\n      },")
    request = "ApiRequest(\n      " + "\n      ".join(req_args) + "\n    )"
    if kind == "stream":
        out.append(f"  {ret} {op.name}({sig}) =>\n    _transport.stream({request});\n\n")
        return "".join(out)
    out.append(f"  {ret} {op.name}({sig}) async {{\n")
    if kind == "void":
        out.append(f"    await _transport.send({request});\n  }}\n\n")
    elif kind == "text":
        out.append(f"    return responseText(await _transport.send({request}));\n  }}\n\n")
    elif kind == "bytes":
        out.append(f"    return (await _transport.send({request})).bodyBytes;\n  }}\n\n")
    else:
        out.append(f"    final response = await _transport.send({request});\n")
        out.append(f"    return decodeResponse(response, {dstr(op.id)}, (json) => "
                   f"{decode(rt, 'json', dstr(op.id))});\n  }}\n\n")
    return "".join(out)


def emit_api(tag, ops, tag_desc):
    out = [doc(tag_desc or f"The `{tag}` operations.")]
    cls = tag_class(tag)
    out.append(f"class {cls} {{\n  const {cls}(this._transport);\n\n  final ApiTransport _transport;\n\n")
    for op in ops:
        out.append(emit_op(op))
    out.append("}\n")
    return "".join(out)


