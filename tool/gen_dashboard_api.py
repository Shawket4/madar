def generate(spec, caps_path):
    g = Gen(spec)
    g.build()
    ops = build_ops(g)       # may add inline classes
    files = {}
    model_parts = []
    for name in sorted(g.classes):
        c = g.classes[name]
        if isinstance(c, Model) and c.base:
            continue   # emitted with its union
        if isinstance(c, Enum):
            body = emit_enum(c)
        elif isinstance(c, Union):
            body = emit_union(c, g.classes)
            for vname, kind, _, _, _ in c.variants:
                if kind == "inline":
                    body += "\n" + emit_model(g.classes[vname])
        else:
            body = emit_model(c)
        fn = f"models/{snake(name)}.dart"
        assert fn not in files, fn
        model_parts.append(fn)
        files[fn] = HEADER + "part of '../models.dart';\n\n" + body
    files["models.dart"] = (HEADER + "\n/// Every schema of spec/openapi.json as an immutable Dart class.\n"
                            "library;\n\nimport 'package:meta/meta.dart';\n\n"
                            "import '../codec.dart';\nimport '../transport.dart';\n\n"
                            + "".join(f"part '{p}';\n" for p in model_parts))
    tags = {}
    for op in ops:
        tags.setdefault(op.tag, []).append(op)
    tag_desc = {t["name"]: t.get("description") for t in spec.get("tags", [])}
    api_parts = []
    for tag in sorted(tags):
        fn = f"apis/{snake(tag_class(tag))}.dart"
        api_parts.append(fn)
        files[fn] = HEADER + "part of '../apis.dart';\n\n" + emit_api(tag, tags[tag], tag_desc.get(tag))
    files["apis.dart"] = (HEADER + "\n/// One class per OpenAPI tag; one method per operation.\nlibrary;\n\n"
                          "import '../client_support.dart';\nimport '../codec.dart';\n"
                          "import '../transport.dart';\nimport 'models.dart';\n\n"
                          + "".join(f"part '{p}';\n" for p in api_parts))
    # operation table
    ot = [HEADER, "\n/// One backend operation: what the mock server routes and coverage checks.\n"
          "class ApiOperation {\n  const ApiOperation(this.id, this.method, this.path, this.tag, this.name);\n\n"
          "  /// The spec's operationId (`list_orders`).\n  final String id;\n\n"
          "  /// `GET`, `POST`, `PUT`, `PATCH` or `DELETE`.\n  final String method;\n\n"
          "  /// The path template (`/orders/{id}/void`).\n  final String path;\n\n"
          "  /// The OpenAPI tag (the API class).\n  final String tag;\n\n"
          "  /// The Dart method name (`listOrders`).\n  final String name;\n}\n\n"
          "/// Every operation of the spec, sorted by tag, path and method.\n"
          "const List<ApiOperation> apiOperations = [\n"]
    for op in ops:
        ot.append(f"  ApiOperation({dstr(op.id)}, {dstr(op.method)}, {dstr(op.path)}, {dstr(op.tag)}, "
                  f"{dstr(op.name)}),\n")
    ot.append("];\n")
    files["operations.dart"] = "".join(ot)
    # facade
    fa = [HEADER, "\nimport '../transport.dart';\nimport 'apis.dart';\n\n"
          "/// The whole backend API over one [ApiTransport]: one getter per tag.\n"
          "///\n/// ```dart\n/// final page = await api.orders.listOrders(branchId: id, page: 1);\n/// ```\n"
          "class DashboardApi {\n  DashboardApi(this.transport);\n\n  final ApiTransport transport;\n\n"]
    for tag in sorted(tags):
        getter = camel(tag)
        if getter in DART_RESERVED or getter == "transport":
            getter += "Api"
        fa.append(f"  late final {tag_class(tag)} {getter} = {tag_class(tag)}(transport);\n")
    fa.append("}\n")
    files["facade.dart"] = "".join(fa)
    if caps_path and os.path.exists(caps_path):
        caps, h = parse_caps(caps_path)
        files["mock_capabilities.dart"] = emit_caps(caps, h)
    elif os.path.exists(os.path.join(OUT, "mock_capabilities.dart")):
        files["mock_capabilities.dart"] = None    # keep the existing one
    files.update(emit_test_support(g, ops))
    stats = {"schemas": len(g.S), "classes": len(g.classes), "operations": len(ops),
             "tags": len(tags), "fallbacks": g.inline_any}
    return files, stats


