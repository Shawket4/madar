DART_RESERVED = {
    # reserved words, and the built-in identifiers that are risky as member names
    "assert", "await", "break", "case", "catch", "class", "const", "continue", "default", "do",
    "else", "enum", "extends", "false", "final", "finally", "for", "if", "in", "is", "new", "null",
    "rethrow", "return", "super", "switch", "this", "throw", "true", "try", "var", "void", "while",
    "with", "yield", "abstract", "covariant", "dynamic", "external", "factory", "get", "late",
    "operator", "required", "set", "static", "typedef",
    # names that would shadow types, annotations, Object members or generated members
    "int", "double", "num", "bool", "override", "immutable", "hashCode", "runtimeType",
    "toString", "noSuchMethod", "toJson", "fromJson", "toFiles", "explicitNulls",
}
# Also taken inside an enum class, and inside a generated API method.
ENUM_RESERVED = DART_RESERVED | {"values", "value", "isKnown"}
PARAM_RESERVED = DART_RESERVED | {"response", "json"}
# Identifiers that are only a problem as a member/parameter name, not as a getter on a facade.
DART_CORE_TYPES = {"Map", "List", "Set", "Object", "Function", "Symbol", "Record", "Enum", "Null",
                   "Uri", "DateTime", "Iterable", "Iterator", "Stream", "Future", "Duration",
                   "Error", "Type", "Exception", "Pattern", "Match", "RegExp", "Comparable",
                   "String", "Never", "Sink", "StackTrace", "BigInt"}
RUNTIME_NAMES = {"ApiRequest", "ApiResponse", "ApiException", "ApiTransport", "ApiFilePart",
                 "ApiOperation", "DashboardApi", "MockCapability"}


# ───────────────────────────── naming ─────────────────────────────

def words(s):
    return [w for w in re.split(r"[^A-Za-z0-9]+", s) if w]


def camel(s):
    """lowerCamel exactly as Orval/lodash spells our snake_case operation ids."""
    ws = words(s)
    if not ws:
        return "value"
    out = ws[0][0].lower() + ws[0][1:]
    for w in ws[1:]:
        out += w[0].upper() + w[1:]
    return out


def pascal(s):
    c = camel(s)
    return c[0].upper() + c[1:]


def snake(name):
    s = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name)
    s = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", s)
    return re.sub(r"[^a-z0-9]+", "_", s.lower()).strip("_")


def ident(s, reserved=DART_RESERVED):
    """A safe Dart member/parameter name for wire name [s]."""
    c = camel(s)
    if c[0].isdigit():
        c = "n" + c
    if c in reserved:
        c += "_"
    return c


def dstr(s):
    """A Dart single-quoted string literal."""
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$").replace("\n", "\\n") + "'"


def doc(text, indent=""):
    if not text:
        return ""
    lines = text.strip().replace("*/", "* /").splitlines()
    return "".join(f"{indent}/// {ln}".rstrip() + "\n" for ln in lines)


# ───────────────────────────── types ─────────────────────────────

class T:
    """A Dart type for one schema node."""

    IDENTITY = {"string", "date", "int", "double", "bool", "any", "jsonmap", "bytes"}

    def __init__(self, kind, name=None, item=None, nullable=False):
        self.kind, self.name, self.item, self.nullable = kind, name, item, nullable

    def n(self, nullable=True):
        return T(self.kind, self.name, self.item, self.nullable or nullable)

    def base(self):
        k = self.kind
        if k in ("string", "date"):
            return "String"
        if k == "int":
            return "int"
        if k == "double":
            return "double"
        if k == "bool":
            return "bool"
        if k == "datetime":
            return "DateTime"
        if k == "bytes":
            return "List<int>"
        if k == "file":
            return "ApiFilePart"
        if k == "any":
            return "Object?"
        if k == "jsonmap":
            return "Map<String, Object?>"
        if k in ("model", "enum", "union"):
            return self.name
        if k == "list":
            return f"List<{self.item.dart()}>"
        if k == "map":
            return f"Map<String, {self.item.dart()}>"
        raise ValueError(k)

    def dart(self):
        b = self.base()
        if self.kind == "any" or not self.nullable:
            return b
        return b + "?"

    def identity(self):
        if self.kind in T.IDENTITY:
            return True
        if self.kind in ("list", "map"):
            return self.item.identity()
        return False


def decode(t, expr, path):
    """Dart expression decoding Object? [expr] to [t]; [path] is a Dart string literal."""
    n = "N" if t.nullable else ""
    k = t.kind
    if k in ("string", "date"):
        return f"decString{n}({expr}, {path})"
    if k == "int":
        return f"decInt{n}({expr}, {path})"
    if k == "double":
        return f"decDouble{n}({expr}, {path})"
    if k == "bool":
        return f"decBool{n}({expr}, {path})"
    if k == "datetime":
        return f"decDateTime{n}({expr}, {path})"
    if k == "bytes":
        return f"decBytes{n}({expr}, {path})"
    if k == "any":
        return expr
    if k == "jsonmap":
        return f"decJsonMap{n}({expr}, {path})"
    if k in ("model", "union"):
        return f"decObject{n}({expr}, {path}, {t.name}.fromJson)"
    if k == "enum":
        return f"decEnum{n}({expr}, {path}, {t.name}.fromJson)"
    if k in ("list", "map"):
        fn = "decList" if k == "list" else "decMap"
        ipath = path[:-1] + ("[]'" if k == "list" else "{}'")
        return f"{fn}{n}<{t.item.dart()}>({expr}, {path}, (e) => {decode(t.item, 'e', ipath)})"
    raise ValueError(k)


def encode(t, expr):
    """Dart expression encoding [expr] (of type t, nullable when t.nullable) to JSON."""
    if t.identity():
        return expr
    q = "?" if t.nullable else ""
    k = t.kind
    if k == "datetime":
        return f"encDateTime{'N' if t.nullable else ''}({expr})"
    if k in ("model", "union", "enum"):
        return f"{expr}{q}.toJson()"
    if k == "list":
        return f"{expr}{q}.map((e) => {encode(t.item, 'e')}).toList()"
    if k == "map":
        return f"{expr}{q}.map((k, e) => MapEntry(k, {encode(t.item, 'e')}))"
    if k == "file":
        return expr
    raise ValueError(k)


# ───────────────────────────── schema model ─────────────────────────────

class Field:
    def __init__(self, wire, t, required, doc_text):
        self.wire, self.required, self.doc = wire, required, doc_text
        self.schema_t = t
        # Dart type: optional fields are nullable whatever the schema says.
        self.t = t if required else t.n()
        self.name = ident(wire)


class Model:
    kind = "model"

    def __init__(self, name, fields, doc_text, union_fields=(), base=None, tag=None):
        self.name, self.fields, self.doc = name, fields, doc_text
        self.union_fields = list(union_fields)   # [(dart name, union class)]
        self.base = base                         # sealed union this variant extends
        self.tag = tag                           # (wire, value) discriminator constant
        self.multipart = False


class Enum:
    kind = "enum"

    def __init__(self, name, values, doc_text):
        self.name, self.values, self.doc = name, values, doc_text


class Union:
    kind = "union"

    def __init__(self, name, doc_text):
        self.name, self.doc = name, doc_text
        self.variants = []     # [(class name, 'inline'|'ref', ref name, tag value, required keys)]
        self.disc = None


class Gen:
    def __init__(self, spec):
        self.spec = spec
        self.S = spec["components"]["schemas"]
        self.classes = {}        # name -> Model | Enum | Union
        self.schema_class = {}   # schema name -> class name
        self.inline_any = []     # where an unsupported shape fell back to Object?
        self.multipart = set()
        for p, item in spec["paths"].items():
            for m, op in item.items():
                for ct, c in (op.get("requestBody") or {}).get("content", {}).items():
                    if ct == "multipart/form-data" and "$ref" in c.get("schema", {}):
                        self.multipart.add(c["schema"]["$ref"].split("/")[-1])
        taken = set(self.S) | DART_CORE_TYPES | RUNTIME_NAMES
        for name in sorted(self.S):
            cls = name
            if name in DART_CORE_TYPES or name in RUNTIME_NAMES:
                cls = name + "Model"
            self.schema_class[name] = cls
        self.taken = taken | set(self.schema_class.values())

    # -- classification ---------------------------------------------------
    def ref_name(self, ref):
        return ref.split("/")[-1]

    def schema_kind(self, name):
        s = self.S[name]
        if "enum" in s and s.get("type") in ("string", ["string", "null"]):
            return "enum"
        variants = [v for v in (s.get("oneOf") or s.get("anyOf") or []) if v.get("type") != "null"]
        if len(variants) > 1:
            return "union"
        return "model"

    def resolve(self, s, ctx):
        """T for schema node [s]; ctx names inline classes (Parent + Prop)."""
        if not isinstance(s, dict) or not s:
            return T("any")
        if "$ref" in s:
            name = self.ref_name(s["$ref"])
            return T(self.schema_kind(name), self.schema_class[name])
        for key in ("oneOf", "anyOf"):
            if key in s:
                vs = s[key]
                nonnull = [v for v in vs if v.get("type") != "null"]
                nullable = len(nonnull) < len(vs)
                if len(nonnull) == 1:
                    return self.resolve(nonnull[0], ctx).n(nullable)
                self.inline_any.append(ctx)
                return T("any")
        if "allOf" in s:
            if len(s["allOf"]) == 1:
                return self.resolve(s["allOf"][0], ctx)
            self.inline_any.append(ctx)
            return T("any")
        typ = s.get("type")
        nullable = False
        if isinstance(typ, list):
            nullable = "null" in typ
            rest = [x for x in typ if x != "null"]
            typ = rest[0] if len(rest) == 1 else (None if not rest else "multi")
        fmt = s.get("format")
        if typ == "string":
            if fmt == "date-time":
                t = T("datetime")
            elif fmt == "date":
                t = T("date")
            elif fmt == "binary":
                t = T("bytes")
            else:
                t = T("string")
        elif typ == "integer":
            t = T("int")
        elif typ == "number":
            t = T("double")
        elif typ == "boolean":
            t = T("bool")
        elif typ == "array":
            t = T("list", item=self.resolve(s.get("items") or {}, ctx + "Item"))
        elif typ == "object" or (typ is None and "properties" in s):
            ap = s.get("additionalProperties")
            if s.get("properties"):
                t = T("model", self.inline_model(ctx, s))
            elif isinstance(ap, dict):
                t = T("map", item=self.resolve(ap, ctx + "Value"))
            else:
                t = T("jsonmap")
        else:
            t = T("any")
        return t.n(nullable)

    def inline_model(self, name, s):
        name = self.unique(name)
        fields, uf = self.collect_fields(name, s)
        self.classes[name] = Model(name, fields, s.get("description"), uf)
        return name

    def unique(self, name):
        base, i = name, 2
        while name in self.taken or name in self.classes:
            name = f"{base}{i}"
            i += 1
        self.taken.add(name)
        return name

    def flatten(self, s, seen=()):
        """(properties, required, union refs, description) of an object/allOf node."""
        props, req, unions = {}, [], []
        if "$ref" in s:
            name = self.ref_name(s["$ref"])
            if name in seen:
                return props, req, unions
            if self.schema_kind(name) == "union":
                return props, req, [name]
            return self.flatten(self.S[name], seen + (name,))
        for m in s.get("allOf", []):
            p, r, u = self.flatten(m, seen)
            props.update(p)
            req += [x for x in r if x not in req]
            unions += [x for x in u if x not in unions]
        props.update(s.get("properties") or {})
        req += [x for x in s.get("required", []) if x not in req]
        return props, req, unions

    def collect_fields(self, cls, s, skip=()):
        props, req, unions = self.flatten(s)
        fields = []
        used = set()
        for wire, ps in props.items():
            if wire in skip:
                continue
            t = self.resolve(ps, cls + pascal(wire))
            f = Field(wire, t, wire in req, ps.get("description") if isinstance(ps, dict) else None)
            while f.name in used:
                f.name += "_"
            used.add(f.name)
            fields.append(f)
        uf = []
        for u in unions:
            nm = ident(snake(self.schema_class[u]))
            while nm in used:
                nm += "_"
            used.add(nm)
            uf.append((nm, self.schema_class[u]))
        return fields, uf

    def build(self):
        for name in sorted(self.S):
            s = self.S[name]
            cls = self.schema_class[name]
            kind = self.schema_kind(name)
            if kind == "enum":
                self.classes[cls] = Enum(cls, [v for v in s["enum"] if v is not None],
                                         s.get("description"))
            elif kind == "union":
                self.build_union(cls, s)
            else:
                fields, uf = self.collect_fields(cls, s)
                m = Model(cls, fields, s.get("description"), uf)
                if name in self.multipart:
                    m.multipart = True
                    for f in m.fields:
                        if f.t.kind == "bytes":
                            f.t = T("file", nullable=f.t.nullable)
                            f.schema_t = T("file", nullable=f.schema_t.nullable)
                self.classes[cls] = m

    def build_union(self, cls, s):
        u = Union(cls, s.get("description"))
        self.classes[cls] = u
        variants = [v for v in (s.get("oneOf") or s.get("anyOf")) if v.get("type") != "null"]
        flat = [self.flatten(v) for v in variants]
        # A discriminator: a property every variant pins to one value.
        disc = None
        if flat:
            for wire in flat[0][0]:
                vals = []
                for props, _, _ in flat:
                    p = props.get(wire) or {}
                    if isinstance(p.get("enum"), list) and len(p["enum"]) == 1:
                        vals.append(p["enum"][0])
                    else:
                        vals = None
                        break
                if vals and len(set(vals)) == len(vals):
                    disc = wire
                    break
        u.disc = disc
        for i, (v, (props, req, _)) in enumerate(zip(variants, flat)):
            tag = props[disc]["enum"][0] if disc else None
            if "$ref" in v and disc is None:
                ref = self.ref_name(v["$ref"])
                vname = self.unique(cls + self.schema_class[ref])
                u.variants.append((vname, "ref", self.schema_class[ref], None, req))
            else:
                vname = self.unique(cls + (pascal(str(tag)) if tag is not None else f"Variant{i + 1}"))
                fields, uf = self.collect_fields(vname, v, skip=(disc,) if disc else ())
                m = Model(vname, fields, v.get("description"), uf, base=cls,
                          tag=(disc, tag) if disc else None)
                self.classes[vname] = m
                u.variants.append((vname, "inline", None, tag, req))
        u.unknown = self.unique(cls + "Unknown")


# ───────────────────────────── emit: models ─────────────────────────────

def emit_model(m):
    out = []
    out.append(doc(m.doc))
    ext = f" extends {m.base}" if m.base else ""
    final = "final " if m.base else ""
    out.append(f"@immutable\n{final}class {m.name}{ext} {{\n")
    optional = [f for f in m.fields if not f.required]
    has_nulls = bool(optional)
    params = []
    for f in m.fields:
        params.append(f"{'required ' if f.required and not (f.t.nullable and f.t.kind == 'any') else ''}this.{f.name},")
    for nm, _ in m.union_fields:
        params.append(f"required this.{nm},")
    if has_nulls:
        params.append("this.explicitNulls = const {},")
    if params:
        out.append(f"  const {m.name}({{\n    " + "\n    ".join(params) + "\n  });\n\n")
    else:
        out.append(f"  const {m.name}();\n\n")
    # fromJson
    args = []
    for f in m.fields:
        path = dstr(f"{m.name}.{f.wire}")
        src = f"json[{dstr(f.wire)}]"
        if f.t.kind == "file":
            n = "N" if f.t.nullable else ""
            args.append(f"{f.name}: decFile{n}({src}, {path}, {dstr(f.wire)}),")
        else:
            args.append(f"{f.name}: {decode(f.t, src, path)},")
    for nm, ucls in m.union_fields:
        args.append(f"{nm}: {ucls}.fromJson(json),")
    out.append(f"  factory {m.name}.fromJson(Map<String, Object?> json) => {m.name}(\n    "
               + "\n    ".join(args) + "\n  );\n\n")
    if m.tag:
        out.append(f"  /// Always {dstr(m.tag[1])}: the variant's tag.\n"
                   f"  String get {ident(m.tag[0])} => {dstr(m.tag[1])};\n\n")
    for f in m.fields:
        out.append(doc(f.doc, "  "))
        out.append(f"  final {f.t.dart()} {f.name};\n\n")
    for nm, ucls in m.union_fields:
        out.append(f"  /// The `{ucls}` part of this object (decoded from the same JSON).\n")
        out.append(f"  final {ucls} {nm};\n\n")
    if has_nulls:
        out.append("  /// Wire names of optional fields to send as an explicit `null` when unset\n"
                   "  /// (a PATCH that clears a value). Unset optional fields are omitted.\n"
                   "  final Set<String> explicitNulls;\n\n")
    # toJson
    entries = []
    for nm, _ in m.union_fields:
        entries.append(f"...{nm}.toJson(),")
    if m.tag:
        entries.append(f"{dstr(m.tag[0])}: {dstr(m.tag[1])},")
    for f in m.fields:
        if f.t.kind == "file":
            continue
        if f.required:
            entries.append(f"{dstr(f.wire)}: {encode(f.t, f.name)},")
        else:
            entries.append(f"if ({f.name} != null || explicitNulls.contains({dstr(f.wire)})) "
                           f"{dstr(f.wire)}: {encode(f.t, f.name)},")
    over = "@override\n  " if m.base else ""
    body = ("{\n    " + "\n    ".join(entries) + "\n  }") if entries else "{}"
    out.append(f"  {over}Map<String, Object?> toJson() => <String, Object?>{body};\n\n")
    if m.multipart:
        parts = []
        for f in m.fields:
            if f.t.kind == "file":
                if f.t.nullable:
                    parts.append(f"if ({f.name} != null) filePartAs({f.name}!, {dstr(f.wire)}),")
                else:
                    parts.append(f"filePartAs({f.name}, {dstr(f.wire)}),")
        out.append("  /// The file parts of this multipart body.\n"
                   "  List<ApiFilePart> toFiles() => [\n    " + "\n    ".join(parts) + "\n  ];\n\n")
    out.append(f"  @override\n  String toString() => '{m.name}(${{toJson()}})';\n")
    out.append("}\n")
    return "".join(out)


def enum_member(v, used):
    c = camel(str(v)) if str(v) else "empty"
    if not c or c[0].isdigit():
        c = "v" + c
    if c in ENUM_RESERVED:
        c += "_"
    while c in used:
        c += "_"
    used.add(c)
    return c


def emit_enum(e):
    used = set()
    members = [(enum_member(v, used), v) for v in e.values]
    out = [doc(e.doc)]
    out.append(f"/// Unknown values from a newer server are kept (`isKnown` is false).\n")
    out.append(f"@immutable\nfinal class {e.name} {{\n")
    out.append(f"  const {e.name}._(this.value);\n\n")
    out.append(f"  factory {e.name}.fromJson(String value) {{\n"
               f"    for (final v in values) {{\n      if (v.value == value) return v;\n    }}\n"
               f"    return {e.name}._(value);\n  }}\n\n")
    for m, v in members:
        out.append(f"  static const {m} = {e.name}._({dstr(str(v))});\n")
    out.append(f"\n  static const List<{e.name}> values = [{', '.join(m for m, _ in members)}];\n\n")
    out.append("  final String value;\n\n")
    out.append("  bool get isKnown => values.contains(this);\n\n")
    out.append("  String toJson() => value;\n\n")
    out.append(f"  @override\n  bool operator ==(Object other) => other is {e.name} && other.value == value;\n\n")
    out.append("  @override\n  int get hashCode => value.hashCode;\n\n")
    out.append("  @override\n  String toString() => value;\n}\n")
    return "".join(out)


def emit_union(u, classes):
    out = [doc(u.doc)]
    out.append(f"@immutable\nsealed class {u.name} {{\n  const {u.name}();\n\n")
    out.append(f"  factory {u.name}.fromJson(Map<String, Object?> json) {{\n")
    if u.disc:
        out.append(f"    switch (json[{dstr(u.disc)}]) {{\n")
        for vname, kind, ref, tag, _ in u.variants:
            out.append(f"      case {dstr(str(tag))}:\n        return {vname}.fromJson(json);\n")
        out.append("    }\n")
    else:
        for vname, kind, ref, tag, req in u.variants:
            cond = " && ".join(f"json.containsKey({dstr(k)})" for k in req) or "true"
            make = f"{vname}({ref}.fromJson(json))" if kind == "ref" else f"{vname}.fromJson(json)"
            out.append(f"    if ({cond}) return {make};\n")
    out.append(f"    return {u.unknown}(json);\n  }}\n\n")
    out.append("  Map<String, Object?> toJson();\n}\n\n")
    for vname, kind, ref, tag, req in u.variants:
        if kind == "ref":
            out.append(f"/// The `{ref}` case of [{u.name}].\n@immutable\n"
                       f"final class {vname} extends {u.name} {{\n"
                       f"  const {vname}(this.value);\n\n  final {ref} value;\n\n"
                       f"  @override\n  Map<String, Object?> toJson() => value.toJson();\n\n"
                       f"  @override\n  String toString() => '{vname}($value)';\n}}\n\n")
    out.append(f"/// A [{u.name}] this client does not know (a newer server); the raw JSON is kept.\n"
               f"@immutable\nfinal class {u.unknown} extends {u.name} {{\n"
               f"  const {u.unknown}(this.json);\n\n  final Map<String, Object?> json;\n\n"
               f"  @override\n  Map<String, Object?> toJson() => json;\n\n"
               f"  @override\n  String toString() => '{u.unknown}($json)';\n}}\n")
    return "".join(out)


