    out.append("class MockCapability {\n  const MockCapability(this.key, this.group, this.tier, this.risk, "
               "this.defaults, this.core, this.en, this.ar);\n\n")
    out.append("  final String key;\n  final String group;\n  final String tier;\n  final String risk;\n"
               "  final List<String> defaults;\n  final List<String> core;\n  final String en;\n"
               "  final String ar;\n}\n\n")
