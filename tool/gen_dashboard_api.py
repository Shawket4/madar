def parse_caps(path):
    src = open(path, encoding="utf-8").read()
    caps = []
    for line in src.splitlines():
        line = line.strip()
        if not line.startswith("{ id:"):
            continue
        def field(name, pat=r'"((?:[^"\\]|\\.)*)"'):
            mm = re.search(r"\b" + name + r": " + pat, line)
            return mm.group(1) if mm else None
        def arr(name):
            mm = re.search(r"\b" + name + r": \[([^\]]*)\]", line)
            return re.findall(r'"([^"]+)"', mm.group(1)) if mm else []
        caps.append({
            "key": field("key"), "group": field("group"), "tier": field("tier"),
            "risk": field("risk"), "defaults": arr("defaults"), "core": arr("core"),
            "en": json.loads('"' + field("en") + '"'), "ar": json.loads('"' + field("ar") + '"'),
        })
    hash_m = re.search(r'SPEC_HASH = "([^"]+)"', src)
    return caps, (hash_m.group(1) if hash_m else "")


def emit_caps(caps, spec_hash):
    out = [HEADER, "// Source: MadarDashboard/src/generated/capabilities.ts", f" (SPEC_HASH {spec_hash}).\n\n"]
