SAMPLE_UUID = "3f0c9d2e-5b7a-4c1d-8e9f-0a1b2c3d4e5f"
SAMPLE_TIME = "2026-10-08T07:00:00.000Z"
MAX_DEPTH = 3


class Sampler:
    """A deterministic JSON sample for every schema (fixtures for round trips)."""

    def __init__(self, g):
        self.g = g

    def value(self, s, depth, multipart=False):
        g = self.g
        if depth > 14:
            raise ValueError("sample recursion too deep")
        if not isinstance(s, dict) or not s:
            return "any"
        if "$ref" in s:
            name = g.ref_name(s["$ref"])
            return self.schema(name, depth)
        for key in ("oneOf", "anyOf"):
            if key in s:
                nonnull = [v for v in s[key] if v.get("type") != "null"]
                return self.value(nonnull[0], depth, multipart) if nonnull else None
        if "allOf" in s:
            return self.obj(s, depth)
        typ = s.get("type")
        if isinstance(typ, list):
            rest = [x for x in typ if x != "null"]
            typ = rest[0] if len(rest) == 1 else None
        fmt = s.get("format")
        if typ == "string":
            if isinstance(s.get("enum"), list) and s["enum"]:
                return s["enum"][0]
            if fmt == "date-time":
                return SAMPLE_TIME
            if fmt == "date":
                return "2026-10-08"
            if fmt == "uuid":
                return SAMPLE_UUID
            if fmt == "binary":
                return {"filename": "image.png", "bytes": [137, 80, 78, 71]} if multipart else [1, 2, 3]
            if fmt == "email":
                return "nour@sabah.test"
            return "text"
        if typ == "integer":
            return 7
        if typ == "number":
            return 1.5
        if typ == "boolean":
            return True
        if typ == "array":
            if depth >= MAX_DEPTH:
                return []
            return [self.value(s.get("items") or {}, depth + 1, multipart)]
        if typ == "object" or (typ is None and "properties" in s):
            if s.get("properties"):
                return self.obj(s, depth)
            ap = s.get("additionalProperties")
            if isinstance(ap, dict):
                return {} if depth >= MAX_DEPTH else {"key": self.value(ap, depth + 1)}
            return {"a": 1}
        return "any"

    def schema(self, name, depth):
        g = self.g
        kind = g.schema_kind(name)
        s = g.S[name]
        if kind == "enum":
            return s["enum"][0]
        if kind == "union":
            variants = [v for v in (s.get("oneOf") or s.get("anyOf")) if v.get("type") != "null"]
            return self.obj(variants[0], depth)
        return self.obj(s, depth, multipart=name in g.multipart)

    def obj(self, s, depth, multipart=False):
        props, req, unions = self.g.flatten(s)
        out = {}
        for u in unions:
            out.update(self.schema(u, depth))
        for k, p in props.items():
            if depth >= MAX_DEPTH and k not in req:
                continue
            out[k] = self.value(p, depth + 1, multipart)
        return out


def dart_value(g, t, class_schema):
    """A Dart expression of type [t] for an operation-call fixture."""
    k = t.kind
    if k == "string":
        return "'text'"
    if k == "date":
        return "'2026-10-08'"
    if k == "int":
        return "7"
    if k == "double":
        return "1.5"
    if k == "bool":
        return "true"
    if k == "datetime":
        return "DateTime.utc(2026, 10, 8, 7)"
    if k == "bytes":
        return "const [1, 2, 3]"
    if k == "file":
        return "const ApiFilePart(field: 'file', filename: 'image.png', bytes: [137, 80, 78, 71])"
    if k == "any":
        return "null"
    if k == "jsonmap":
        return "const <String, Object?>{}"
    if k in ("model", "union"):
        return f"{t.name}.fromJson(s({dstr(class_schema.get(t.name, t.name))}))"
    if k == "enum":
        return f"{t.name}.values.first"
    if k == "list":
        return f"[{dart_value(g, t.item, class_schema)}]"
    if k == "map":
        return f"{{'key': {dart_value(g, t.item, class_schema)}}}"
    raise ValueError(k)


