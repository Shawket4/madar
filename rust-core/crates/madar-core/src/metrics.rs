/// The branch-local days a preset covers on `today` (weeks start on SATURDAY,
/// [`crate::timefmt::WEEK_START`], like the backend's analytics presets).
pub(crate) fn preset_days(
    preset: &str,
    today: NaiveDate,
    custom_from: Option<&str>,
    custom_to: Option<&str>,
) -> CoreResult<(NaiveDate, NaiveDate)> {
    let bad = |detail: &str| CoreError::Validation { field: "metrics.window".into(), detail: detail.into() };
    Ok(match preset {
        "today" => (today, today),
        "yesterday" => (today - Duration::days(1), today - Duration::days(1)),
        "this_week" => (crate::timefmt::week_start(today), today),
        "this_month" => (today.with_day(1).unwrap_or(today), today),
        "last_7_days" => (today - Duration::days(6), today),
        "custom" => {
            let parse = |d: Option<&str>| d.and_then(|d| NaiveDate::parse_from_str(d.trim(), "%Y-%m-%d").ok());
            let (Some(from), Some(to)) = (parse(custom_from), parse(custom_to)) else {
                return Err(bad("a custom window needs two days (YYYY-MM-DD)"));
            };
            if to < from {
                return Err(bad("the last day is before the first"));
            }
            if (to - from).num_days() >= MAX_DAYS {
                return Err(bad("a window is at most 366 days"));
            }
            (from, to)
        }
        _ => return Err(bad("unknown preset")),
    })
}

/// Since when this device holds EVERY sale of `branch`: the ledger window of
/// its last complete snapshot, but never before what retention keeps. `None`
/// when the device has never taken a snapshot of the branch.
pub(crate) fn held_since(conn: &Connection, branch: &str, now: DateTime<Utc>) -> CoreResult<Option<DateTime<Utc>>> {
    let window: Option<Option<String>> = conn
        .query_row("SELECT window_from FROM sync_streams WHERE stream = ?1", [format!("branch:{branch}")], |r| r.get(0))
        .optional()?;
    let Some(window) = window.flatten().as_deref().and_then(instant) else { return Ok(None) };
    let kept = now - Duration::days(crate::ledger::retention::KEEP_DAYS);
    Ok(Some(window.max(kept)))
}

fn share(part: i64, whole: i64) -> f64 {
    if whole <= 0 || part <= 0 {
        0.0
    } else {
        (part as f64 / whole as f64).clamp(0.0, 1.0)
    }
}

/// The inputs a view is built from beside the figures.
pub(crate) struct ViewCtx<'a> {
    pub preset: &'a str,
    pub from: NaiveDate,
    pub to: NaiveDate,
    pub tz: chrono_tz::Tz,
    pub locale: &'a str,
    pub currency_code: String,
    pub source_device: bool,
    pub held_since: Option<DateTime<Utc>>,
    pub now: DateTime<Utc>,
}

pub(crate) fn view(f: &Figures, ctx: &ViewCtx<'_>, label: &dyn Fn(&str) -> String) -> PosMetricsView {
    let tr = |k: &str| crate::i18n::tr(ctx.locale, k);
    let day = |d: NaiveDate| {
        let (start, _) = crate::timefmt::local_day_bounds(ctx.tz, d);
        crate::timefmt::format_in(ctx.tz, &start.to_rfc3339(), crate::timefmt::TimeStyle::DateShort, ctx.locale)
    };
    let range_label =
        if ctx.from == ctx.to { day(ctx.from) } else { format!("{} – {}", day(ctx.from), day(ctx.to)) };
    let offline_note = ctx.source_device.then(|| match ctx.held_since {
        Some(since) => {
            let days = ((ctx.now - since).num_seconds() + 86_399).div_euclid(86_400).max(1);
            tr("metrics.offline_note").replace("{days}", &days.to_string()).replace(
                "{since}",
                &crate::timefmt::format_in(ctx.tz, &since.to_rfc3339(), crate::timefmt::TimeStyle::DateTime, ctx.locale),
            )
        }
        None => tr("metrics.offline_nothing_held"),
    });
    let items_note = (f.items_missing > 0)
        .then(|| tr("metrics.items_missing").replace("{count}", &f.items_missing.to_string()));
    let tender_total: i64 = f.tenders.iter().map(|t| t.amount).sum();
    let top_qty = f.top_items.first().map(|i| i.quantity).unwrap_or(0);
    let peak = f.hourly.iter().map(|h| h.1).max().unwrap_or(0);
    PosMetricsView {
        preset: ctx.preset.to_string(),
        from_date: ctx.from.to_string(),
        to_date: ctx.to.to_string(),
        range_label,
        source: if ctx.source_device { "device" } else { "server" }.to_string(),
        offline_note,
        items_note,
        currency_code: ctx.currency_code.clone(),
        net_sales_minor: f.net_sales,
        gross_sales_minor: f.gross_sales,
        refunded_amount_minor: f.refunded_amount,
        order_count: f.order_count,
        average_ticket_minor: f.average_ticket,
        tenders: f
            .tenders
            .iter()
            .map(|t| MetricsTenderView {
                method: t.method.clone(),
                label: label(&t.method),
                amount_minor: t.amount,
                order_count: t.order_count,
                share: share(t.amount, tender_total),
            })
            .collect(),
        voided_count: f.voided_count,
        voided_amount_minor: f.voided_amount,
        refunded_orders_count: f.refunded_orders_count,
        refunds_issued_count: f.refunds_issued_count,
        refunds_issued_amount_minor: f.refunds_issued_amount,
        top_items: f
            .top_items
            .iter()
            .map(|it| MetricsItemView {
                name: it.item_name.clone(),
                quantity: it.quantity,
                revenue_minor: it.revenue,
                share: share(it.quantity, top_qty),
            })
            .collect(),
        hourly: f
            .hourly
            .iter()
            .enumerate()
            .map(|(h, (count, net))| MetricsHourView {
                hour: h as i32,
                label: format!("{h:02}"),
                order_count: *count,
                net_sales_minor: *net,
                share: share(*net, peak),
            })
            .collect(),
    }
}

// ── The screen's reads ───────────────────────────────────────────────────────

impl crate::MadarCore {
    /// The preset chips, in order, in the till's language.
    pub fn pos_metrics_presets(&self) -> Vec<MetricsPresetView> {
        let locale = self.current_locale();
        PRESETS
            .iter()
            .map(|k| MetricsPresetView { key: k.to_string(), label: crate::i18n::tr(&locale, &format!("metrics.preset.{k}")) })
            .collect()
    }

    fn metrics_gate(&self) -> Result<(), CoreError> {
        if self.can(CAP.to_string()) {
            Ok(())
        } else {
            Err(CoreError::Forbidden { resource: "reports".into(), action: "pos_metrics".into() })
        }
    }

    /// The Metrics screen for a preset (`custom` takes two `YYYY-MM-DD` days).
    /// Online: the server's figures in one call, under the read timeout. Offline
    /// or when that call fails: [`Self::pos_metrics_on_device`]. A refusal from
    /// the server (403/401) is returned as is, never papered over.
    pub async fn pos_metrics(
        &self,
        preset: String,
        custom_from: Option<String>,
        custom_to: Option<String>,
    ) -> Result<PosMetricsView, CoreError> {
        self.metrics_gate()?;
        let tz = crate::timefmt::branch_tz(&self.store);
        let now = Utc::now();
        let (from, to) =
            preset_days(&preset, now.with_timezone(&tz).date_naive(), custom_from.as_deref(), custom_to.as_deref())?;
        let online = self.current_session().map(|s| s.online).unwrap_or(false);
        if online {
            let branch = self.session_branch_id()?;
            let config = self.api.config();
            let call = madar_api::apis::reports_api::branch_pos_metrics(
                &config,
                madar_api::apis::reports_api::BranchPosMetricsParams { branch_id: branch, from, to },
            );
            match crate::ledger_ops::within(call).await {
                Ok(report) => {
                    crate::timefmt::remember_tz(&self.store, &report.timezone);
                    let tz = report.timezone.parse().unwrap_or(tz);
                    return Ok(self.metrics_view(&Figures::from_report(&report), &preset, from, to, tz, false, None, now));
                }
                Err(e @ (CoreError::Forbidden { .. } | CoreError::Unauthenticated { .. })) => return Err(e),
                Err(_) => {}
            }
        }
        self.pos_metrics_on_device(preset, custom_from, custom_to)
    }

    /// The same figures from this device's rows only (never the network), for
    /// the part of the window the device holds, with the note that says so.
    pub fn pos_metrics_on_device(
        &self,
        preset: String,
        custom_from: Option<String>,
        custom_to: Option<String>,
    ) -> Result<PosMetricsView, CoreError> {
        self.metrics_gate()?;
        let tz = crate::timefmt::branch_tz(&self.store);
        let now = Utc::now();
        let (from, to) =
            preset_days(&preset, now.with_timezone(&tz).date_naive(), custom_from.as_deref(), custom_to.as_deref())?;
        let branch = self.session_branch_id()?;
        let window_from = crate::timefmt::local_day_bounds(tz, from).0.with_timezone(&Utc);
        let window_to = crate::timefmt::local_day_bounds(tz, to).1.with_timezone(&Utc);
        let (held, figures) = self.store.with_conn(|c| {
            let held = held_since(c, &branch, now)?;
            let start = held.map_or(window_from, |h| h.max(window_from));
            let f = if start < window_to { local_figures(c, &branch, tz, start, window_to)? } else { local_figures(c, &branch, tz, window_to, window_to)? };
            Ok((held, f))
        })?;
        Ok(self.metrics_view(&figures, &preset, from, to, tz, true, held, now))
    }

    #[allow(clippy::too_many_arguments)]
    fn metrics_view(
        &self,
        f: &Figures,
        preset: &str,
        from: NaiveDate,
        to: NaiveDate,
        tz: chrono_tz::Tz,
        source_device: bool,
        held: Option<DateTime<Utc>>,
        now: DateTime<Utc>,
    ) -> PosMetricsView {
        let locale = self.current_locale();
        let ctx = ViewCtx {
            preset,
            from,
            to,
            tz,
            locale: &locale,
            currency_code: self.current_session().map(|s| s.currency_code).unwrap_or_default(),
            source_device,
            held_since: held,
            now,
        };
        view(f, &ctx, &|m| self.payment_method_label(m.to_string()))
    }
}

