//! The till's Metrics screen (capability `reports.pos_metrics`).
//!
//! Online it is ONE person-triggered call, `GET /reports/branches/{id}/pos-metrics`
//! (MadarRust `reports::pos_metrics`), under the usual read timeout. Offline, or
//! while that call fails, the same figures are computed from the local ledger
//! for the part of the window this device holds, and the view says so.
//!
//! The definitions are the backend's `branch_sales` ones:
//! * a SOLD sale is neither voided nor refunded in full;
//! * `net_sales` = Σ (total − every refund against the sale) over sold sales;
//! * tenders are the sold sales' payment legs by method (goods only, no tips);
//! * top items are the sold sales' lines grouped by (menu item or bundle, name),
//!   by quantity, then revenue, then name (byte order, `COLLATE "C"`);
//! * hours are the branch's local hours.
//!
//! Days are cut at local midnight in the branch timezone
//! ([`crate::timefmt::local_day_bounds`], the backend's `service_day_bounds`).
//! `tests/fixtures/pos_metrics_vectors.json` is generated by the backend from
//! feed rows and asserted here field by field.

